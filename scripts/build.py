#!/usr/bin/env python3
"""Build the Desktop half from its sources.

desktop/plugin.js must be ONE plain ES module (the Desktop loader resolves only
`@hermes/plugin-sdk`, `react` and `react/jsx-runtime`), so the sources in
desktop/src/*.js are fragments without imports or exports, concatenated in file
name order after a fixed header that holds the imports and the card schema.

Also generates desktop/cards.d.ts (TypeScript types) from the same schema.

    python3 scripts/build.py          # write both files
    python3 scripts/build.py --check  # fail if either is out of date
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = ROOT / "hui_cards" / "cards.schema.json"
SRC = ROOT / "desktop" / "src"
OUT_JS = ROOT / "desktop" / "plugin.js"
OUT_DTS = ROOT / "desktop" / "cards.d.ts"

HEADER = """\
// hermes-ui-cards: Desktop half. GENERATED by scripts/build.py from desktop/src/*.js
// and hui_cards/cards.schema.json. Do not edit by hand; edit the sources and rebuild.
import * as sdk from '@hermes/plugin-sdk'
import { useCallback, useEffect, useId, useMemo, useRef, useState } from 'react'
import { Fragment, jsx, jsxs } from 'react/jsx-runtime'

const SCHEMA = %s
"""


def build_js() -> str:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    parts = [HEADER % json.dumps(schema, ensure_ascii=False, separators=(",", ":"))]
    for path in sorted(SRC.glob("*.js")):
        body = path.read_text(encoding="utf-8").rstrip() + "\n"
        parts.append(f"\n// ── {path.name} ──\n{body}")
    return "".join(parts)


# ── TypeScript types ──

def _ts_name(card_type: str) -> str:
    return "".join(p.capitalize() for p in card_type.split("_")) + "Card"


def _ts(spec: dict, defs: dict, indent: str) -> str:
    if "$ref" in spec:
        merged = dict(defs[spec["$ref"]])
        merged.update({k: v for k, v in spec.items() if k != "$ref"})
        spec = merged
    if "enum" in spec:
        return " | ".join(json.dumps(v) for v in spec["enum"])
    types = spec.get("type")
    types = types if isinstance(types, list) else [types]
    out = []
    for t in types:
        if t == "string":
            out.append("string")
        elif t in ("number", "integer"):
            out.append("number")
        elif t == "boolean":
            out.append("boolean")
        elif t == "null":
            out.append("null")
        elif t == "array":
            inner = _ts(spec.get("items", {}), defs, indent)
            out.append(f"Array<{inner}>")
        elif t == "object":
            out.append(_ts_object(spec, defs, indent))
    return " | ".join(out) or "unknown"


def _ts_object(spec: dict, defs: dict, indent: str, extra: str = "") -> str:
    req = set(spec.get("required", []))
    lines = ["{"]
    if extra:
        lines.append(extra)
    for key, prop in spec.get("properties", {}).items():
        desc = prop.get("description") or (defs.get(prop.get("$ref"), {}).get("description"))
        if desc:
            lines.append(f"{indent}  /** {desc} */")
        opt = "" if key in req else "?"
        lines.append(f"{indent}  {key}{opt}: {_ts(prop, defs, indent + '  ')}")
    lines.append(indent + "}")
    return "\n".join(lines)


def build_dts() -> str:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    defs = schema["definitions"]
    out = [
        "// GENERATED by scripts/build.py from hui_cards/cards.schema.json. Do not edit by hand.",
        "// Card shapes after validation (ids filled in, defaults applied).",
        "",
        "export interface CardCommon {",
        "  /** Unique id the tool assigned, e.g. \"trip-style-3f9a1c\". */",
        "  cardId: string",
    ]
    for key, prop in schema["common"]["properties"].items():
        if key == "type":
            continue
        out.append(f"  /** {prop['description']} */")
        out.append(f"  {key}?: string")
    out += ["}", ""]
    names = []
    for ctype, spec in schema["cards"].items():
        name = _ts_name(ctype)
        names.append(name)
        out.append(f"/** {spec['summary']} */")
        body = _ts_object(spec, defs, "", extra=f"  type: {json.dumps(ctype)}")
        out.append(f"export interface {name} extends CardCommon {body}")
        out.append("")
    out.append("export type Card =\n  | " + "\n  | ".join(names))
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    targets = {OUT_JS: build_js(), OUT_DTS: build_dts()}
    stale = []
    for path, text in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("out of date (run python3 scripts/build.py): " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
